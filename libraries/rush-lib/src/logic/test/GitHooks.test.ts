import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { spawnSync } from 'node:child_process';
import { AlreadyReportedError, FileSystem } from '@rushstack/node-core-library';
import { StringBufferTerminalProvider, Terminal } from '@rushstack/terminal';

import type { RushConfiguration } from '../../api/RushConfiguration';
import { Git } from '../Git';
import { GitHooks } from '../GitHooks';

const lfsHookNames: string[] = ['post-checkout', 'post-commit', 'post-merge', 'pre-push'];
const marker: string = '# Generated by Rush. Do not edit.\n';
const itWithGitLfs: typeof it = spawnSync('git', ['lfs', 'version']).status === 0 ? it : it.skip;

describe(GitHooks.name, () => {
  let repoFolder: string;
  let hookSource: string;
  let hookDestination: string;
  let rushConfiguration: RushConfiguration;
  let terminalProvider: StringBufferTerminalProvider;
  let terminal: Terminal;

  beforeEach(() => {
    repoFolder = fs.mkdtempSync(path.join(os.tmpdir(), 'rush-git-hooks-'));
    hookSource = path.join(repoFolder, 'common/git-hooks');
    hookDestination = path.join(repoFolder, '.git/hooks');
    rushConfiguration = {
      commonFolder: path.join(repoFolder, 'common'),
      rushJsonFolder: repoFolder
    } as RushConfiguration;
    terminalProvider = new StringBufferTerminalProvider();
    terminal = new Terminal(terminalProvider);
    jest.spyOn(Git.prototype, 'getHooksFolder').mockReturnValue(hookDestination);
    jest.spyOn(Git.prototype, 'getIsHooksPathDefaultAsync').mockResolvedValue(true);
  });

  afterEach(() => {
    jest.restoreAllMocks();
    FileSystem.deleteFolder(repoFolder);
  });

  function writeHook(folder: string, name: string, content: string = '#!/bin/sh\nexit 0\n'): void {
    const filePath: string = path.join(folder, name);
    FileSystem.deleteFile(filePath);
    FileSystem.writeFile(filePath, content, { ensureFolderExists: true });
  }

  function readHook(name: string): string {
    return FileSystem.readFile(path.join(hookDestination, name));
  }

  async function installAsync(bypassPolicy: boolean = false): Promise<void> {
    await GitHooks.installAsync(rushConfiguration, terminal, bypassPolicy);
  }

  function runGit(...args: string[]): string {
    const result = spawnSync('git', args, {
      cwd: repoFolder,
      encoding: 'utf8',
      env: {
        ...process.env,
        GIT_CONFIG_NOSYSTEM: '1',
        GIT_CONFIG_GLOBAL: os.devNull
      }
    });
    if (result.status !== 0) {
      throw new Error(`git ${args.join(' ')} failed: ${result.error || result.stderr}`);
    }

    return result.stdout;
  }

  it('preserves unmanaged hooks, samples, and subdirectories', async () => {
    writeHook(hookSource, 'pre-commit', '#!/bin/sh\r\nexit 0\r\n');
    writeHook(hookSource, 'commit-msg.sample');
    for (const name of [...lfsHookNames, 'commit-msg', 'pre-commit.sample']) {
      writeHook(hookDestination, name, `unmanaged ${name}`);
    }

    writeHook(path.join(hookDestination, 'other-tool'), 'config', 'other tool data');
    await installAsync();
    for (const name of [...lfsHookNames, 'commit-msg', 'pre-commit.sample']) {
      expect(readHook(name)).toBe(`unmanaged ${name}`);
    }

    expect(FileSystem.readFile(path.join(hookDestination, 'other-tool/config'))).toBe('other tool data');
    expect(readHook('pre-commit')).toContain(marker);
    expect(readHook('pre-commit')).toContain('../../common/git-hooks/pre-commit');
    expect(FileSystem.readFile(path.join(hookSource, 'pre-commit'))).not.toContain('\r');
    expect(terminalProvider.getWarningOutput()).toBe('');
  });

  it('refreshes its own hooks and removes obsolete delegates', async () => {
    writeHook(hookSource, 'pre-commit');
    writeHook(hookSource, 'commit-msg');
    await installAsync();
    const originalPreCommit: string = readHook('pre-commit');
    FileSystem.deleteFile(path.join(hookSource, 'commit-msg'));
    await installAsync();
    expect(readHook('pre-commit')).toBe(originalPreCommit);
    expect(FileSystem.exists(path.join(hookDestination, 'commit-msg'))).toBe(false);
  });

  it.each(['empty', 'samples only', 'missing'])('cleans up when the source folder is %s', async (state) => {
    writeHook(hookSource, 'pre-commit');
    await installAsync();
    FileSystem.deleteFolder(hookSource);
    if (state === 'empty') {
      FileSystem.ensureFolder(hookSource);
    } else if (state === 'samples only') {
      writeHook(hookSource, 'commit-msg.sample');
    }

    writeHook(hookDestination, 'pre-push', 'unmanaged LFS hook');
    await installAsync();
    expect(FileSystem.exists(path.join(hookDestination, 'pre-commit'))).toBe(false);
    expect(readHook('pre-push')).toBe('unmanaged LFS hook');
  });

  it('recognizes unmodified legacy delegates but preserves edited delegates', async () => {
    writeHook(hookSource, 'pre-commit');
    writeHook(hookSource, 'commit-msg');
    await installAsync();
    const legacyHook: string = `#!/usr/bin/env bash
set -e
SCRIPT_DIR="$( cd "$( dirname "\${BASH_SOURCE[0]}" )" &> /dev/null && pwd )"
SCRIPT_IMPLEMENTATION_PATH="$SCRIPT_DIR/../../common/git-hooks/pre-commit"

if [[ -f "$SCRIPT_IMPLEMENTATION_PATH" ]]; then
  "$SCRIPT_IMPLEMENTATION_PATH" $@
else
  echo "The pre-commit Git hook no longer exists in your version of the repo. Run 'rush install' or 'rush update' to refresh your installed Git hooks." >&2
fi

`;
    writeHook(hookDestination, 'pre-commit', legacyHook);
    const editedHook: string = readHook('commit-msg') + '\necho custom logic\n';
    writeHook(hookDestination, 'commit-msg', editedHook);
    FileSystem.deleteFile(path.join(hookSource, 'commit-msg'));
    await installAsync();
    expect(readHook('pre-commit')).toBe(
      legacyHook.replace('#!/usr/bin/env bash\n', '#!/usr/bin/env bash\n' + marker)
    );
    expect(readHook('commit-msg')).toBe(editedHook);
    writeHook(hookDestination, 'pre-commit', legacyHook);
    FileSystem.deleteFolder(hookSource);
    await installAsync();
    expect(FileSystem.exists(path.join(hookDestination, 'pre-commit'))).toBe(false);
    expect(readHook('commit-msg')).toBe(editedHook);
  });

  it('reports all collisions before changing any hook', async () => {
    writeHook(hookSource, 'pre-commit');
    await installAsync();
    FileSystem.deleteFile(path.join(hookSource, 'pre-commit'));
    writeHook(hookSource, 'commit-msg', '#!/bin/sh\r\nexit 0\r\n');
    writeHook(hookSource, 'pre-push');
    writeHook(hookDestination, 'pre-push', 'canonical LFS hook');
    await expect(installAsync()).rejects.toThrow(AlreadyReportedError);
    expect(readHook('pre-push')).toBe('canonical LFS hook');
    expect(FileSystem.exists(path.join(hookDestination, 'commit-msg'))).toBe(false);
    expect(readHook('pre-commit')).toContain(marker);
    expect(FileSystem.readFile(path.join(hookSource, 'commit-msg'))).toContain('\r\n');
    expect(terminalProvider.getErrorOutput()).toContain('pre-push');
    expect(terminalProvider.getErrorOutput()).toContain('git lfs install --local');
  });

  it('skips installation on a collision when bypassing policy', async () => {
    writeHook(hookSource, 'pre-commit');
    writeHook(hookSource, 'commit-msg');
    writeHook(hookDestination, 'pre-commit', 'another hook manager');
    await installAsync(true);
    expect(readHook('pre-commit')).toBe('another hook manager');
    expect(FileSystem.exists(path.join(hookDestination, 'commit-msg'))).toBe(false);
    expect(terminalProvider.getWarningOutput()).toContain('Skipping Git hook installation');
  });

  it('does not take ownership of a directory with a matching hook name', async () => {
    writeHook(hookSource, 'pre-commit');
    FileSystem.ensureFolder(path.join(hookDestination, 'pre-commit'));
    await expect(installAsync()).rejects.toThrow(AlreadyReportedError);
    expect(FileSystem.getStatistics(path.join(hookDestination, 'pre-commit')).isDirectory()).toBe(true);
  });

  (process.platform === 'win32' ? it.skip : it)('does not follow symlinked hooks', async () => {
    writeHook(hookSource, 'pre-commit');
    await installAsync();
    const generatedHook: string = readHook('pre-commit');
    const linkTarget: string = path.join(repoFolder, 'linked-hook');
    FileSystem.move({ sourcePath: path.join(hookDestination, 'pre-commit'), destinationPath: linkTarget });
    fs.symlinkSync(linkTarget, path.join(hookDestination, 'pre-commit'));
    await expect(installAsync()).rejects.toThrow(AlreadyReportedError);
    expect(FileSystem.readFile(linkTarget)).toBe(generatedHook);
    expect(FileSystem.getLinkStatistics(path.join(hookDestination, 'pre-commit')).isSymbolicLink()).toBe(
      true
    );
  });

  it.each([true, false])('respects core.hooksPath (bypassPolicy=%s)', async (bypassPolicy) => {
    writeHook(hookSource, 'pre-commit');
    jest.spyOn(Git.prototype, 'getIsHooksPathDefaultAsync').mockResolvedValue(false);
    jest.spyOn(Git.prototype, 'getConfigHooksPathAsync').mockResolvedValue('custom-hooks');
    if (bypassPolicy) {
      await installAsync(true);
      expect(terminalProvider.getWarningOutput()).toContain('core.hooksPath=custom-hooks');
    } else {
      await expect(installAsync()).rejects.toThrow(AlreadyReportedError);
      expect(terminalProvider.getErrorOutput()).toContain('core.hooksPath=custom-hooks');
    }

    expect(FileSystem.exists(hookDestination)).toBe(false);
  });

  it('does not clean up delegates when a custom hooksPath is configured', async () => {
    writeHook(hookSource, 'pre-commit');
    await installAsync();
    FileSystem.deleteFolder(hookSource);
    jest.spyOn(Git.prototype, 'getIsHooksPathDefaultAsync').mockResolvedValue(false);
    await installAsync();
    expect(readHook('pre-commit')).toContain(marker);
  });

  it('does nothing outside a Git worktree', async () => {
    writeHook(hookSource, 'pre-commit');
    jest.spyOn(Git.prototype, 'getHooksFolder').mockReturnValue(undefined);
    await installAsync();
    expect(FileSystem.exists(hookDestination)).toBe(false);
  });

  it.each(lfsHookNames)(
    'warns about %s wrappers and retains their LFS delegation when obsolete',
    async (name) => {
      writeHook(hookSource, name);
      await installAsync();
      const delegate: string = readHook(name);
      expect(delegate).toContain(`git lfs ${name} "$@"`);
      expect(terminalProvider.getWarningOutput()).toContain('Azure Pipelines');
      expect(terminalProvider.getWarningOutput()).toContain(name);
      FileSystem.deleteFolder(hookSource);
      // Older Rush versions generated the same delegate without an ownership marker.
      writeHook(hookDestination, name, delegate.replace(marker, ''));
      await installAsync();
      expect(readHook(name)).toBe(delegate.replace(marker, ''));
    }
  );

  itWithGitLfs.each(['lfs first', 'rush first'])(
    'supports repeated LFS checkout/install cycles (%s)',
    async (order) => {
      runGit('init');
      writeHook(hookSource, 'pre-commit');
      if (order === 'rush first') {
        await installAsync();
      }

      runGit('lfs', 'install', '--local');
      const canonicalHooks: string[] = lfsHookNames.map(readHook);
      for (let cycle: number = 0; cycle < 3; cycle++) {
        await installAsync();
        expect(lfsHookNames.map(readHook)).toEqual(canonicalHooks);
        runGit('lfs', 'install', '--local');
        expect(lfsHookNames.map(readHook)).toEqual(canonicalHooks);
      }

      // A real commit exercises the Rush pre-commit hook and the canonical LFS post-commit hook.
      runGit(
        '-c',
        'user.name=Rush Test',
        '-c',
        'user.email=rush-test@example.com',
        'commit',
        '--allow-empty',
        '-m',
        'test'
      );
    }
  );

  itWithGitLfs('rejects a canonical LFS collision without corrupting later checkouts', async () => {
    runGit('init');
    runGit('lfs', 'install', '--local');
    const canonicalHooks: string[] = lfsHookNames.map(readHook);
    writeHook(hookSource, 'pre-push');
    await expect(installAsync()).rejects.toThrow(AlreadyReportedError);
    expect(lfsHookNames.map(readHook)).toEqual(canonicalHooks);
    runGit('lfs', 'install', '--local');
  });

  itWithGitLfs('still uploads LFS objects after installing Rush hooks', async () => {
    runGit('init');
    runGit('lfs', 'install', '--local');
    runGit('lfs', 'track', '*.bin');
    writeHook(hookSource, 'pre-commit');
    await installAsync();
    const content: string = 'An LFS object that must be uploaded, not just a pointer.';
    FileSystem.writeFile(path.join(repoFolder, 'asset.bin'), content);
    runGit('add', '.gitattributes', 'asset.bin');
    runGit(
      '-c',
      'user.name=Rush Test',
      '-c',
      'user.email=rush-test@example.com',
      'commit',
      '-m',
      'LFS object'
    );
    const pointer: string = runGit('show', 'HEAD:asset.bin');
    const oid: string = /oid sha256:([a-f0-9]+)/.exec(pointer)![1];
    const remoteFolder: string = path.join(repoFolder, 'remote.git');
    runGit('init', '--bare', remoteFolder);
    runGit('remote', 'add', 'origin', remoteFolder);
    runGit('push', 'origin', 'HEAD:refs/heads/main');
    const objectPath: string = path.join(remoteFolder, 'lfs/objects', oid.slice(0, 2), oid.slice(2, 4), oid);
    expect(FileSystem.readFile(objectPath)).toBe(content);
  });

  itWithGitLfs('diagnoses incompatible wrappers and supports the documented recovery', async () => {
    runGit('init');
    writeHook(hookSource, 'pre-push');
    await installAsync();
    expect(() => runGit('lfs', 'install', '--local')).toThrow('Hook already exists: pre-push');
    expect(terminalProvider.getWarningOutput()).toContain('before the next checkout');
    FileSystem.deleteFile(path.join(hookSource, 'pre-push'));
    FileSystem.deleteFile(path.join(hookDestination, 'pre-push'));
    runGit('lfs', 'install', '--local');
    const canonicalHooks: string[] = lfsHookNames.map(readHook);
    await installAsync();
    runGit('lfs', 'install', '--local');
    expect(lfsHookNames.map(readHook)).toEqual(canonicalHooks);
  });
});
